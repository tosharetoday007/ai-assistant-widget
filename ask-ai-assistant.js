  /* ============================================================
     STEP 5 — Live search intent detection
     hotel / flight / deal (existing) plus the four newly-wired
     intents: concert, event, destinations, freetours.
     Order matters: more specific patterns are checked before the
     generic "event" pattern so "concert" doesn't fall through to
     the events feed.
  ============================================================ */
  function detectLiveSearchIntent(text) {
    var lower = text.toLowerCase();
    if (/\b(hotel|hotels|stay|accommodation|room|place to stay)\b/.test(lower)) { return 'hotel'; }
    if (/\b(flight|flights|fly|airfare|plane ticket)\b/.test(lower)) { return 'flight'; }
    if (/\b(deal|deals|cheap fare|cheap flight|error fare)\b/.test(lower)) { return 'deal'; }
    if (/\b(concert|concierto|conciertos|gig|live music|band playing)\b/.test(lower)) { return 'concert'; }
    if (/\b(event|events|evento|eventos|what'?s (on|happening)|things to do (tonight|this weekend))\b/.test(lower)) { return 'event'; }
    if (/\b(free walking tour|free tour|walking tour)\b/.test(lower)) { return 'freetours'; }
    if (/\b(top destination|top destinations|best destination|recommend a (city|destination|place)|where should i (go|travel)|bestseller|top activities)\b/.test(lower)) { return 'destinations'; }
    return null;
  }

  function guessCityFromText(text, ctx) {
    // Prefer an explicit city mention in the message; else fall back to
    // the article's classified topic if it's a travel article.
    var words = text.replace(/[^a-zA-Z\s]/g, '').split(/\s+/).filter(function (w) { return w.length > 2; });
    var lastCapitalized = null;
    for (var i = 0; i < words.length; i++) {
      if (/^[A-Z]/.test(words[i])) { lastCapitalized = words[i]; }
    }
    if (lastCapitalized) { return lastCapitalized; }
    if (currentClassification && currentClassification.category === 'travel' && currentClassification.topic) {
      return currentClassification.topic;
    }
    return ctx.title;
  }

  function dealBadgeClass(deal) {
    var d = (deal || 'NORMAL').toUpperCase();
    if (d === 'VERY CHEAP') return 'verycheap';
    if (d === 'CHEAP') return 'cheap';
    return '';
  }

  function handleHotelQuery(cityName) {
    var typingId = showTyping();
    var checkin = new Date(); checkin.setDate(checkin.getDate() + 7);
    var checkout = new Date(); checkout.setDate(checkout.getDate() + 10);
    var cin = checkin.toISOString().slice(0, 10);
    var cout = checkout.toISOString().slice(0, 10);
    var url = GAS_URL + '?action=searchHotels&city=' + encodeURIComponent(cityName) +
      '&checkin=' + cin + '&checkout=' + cout + '&adults=2&currency=USD&stars=all';

    jsonp(url).then(function (data) {
      removeTyping(typingId);
      if (!data || !data.hotels || !data.hotels.length) {
        addMsg('ai', 'No live hotel prices came back for ' + escapeHtml(cityName) + ' right now — try different dates or check <a href="https://www.latestfoto.com/p/accommodation.html" target="_blank" rel="noopener">our accommodation page</a>.');
        return;
      }
      var sym = CURRENCY_SYM.USD;
      var cards = data.hotels.slice(0, 4).map(function (h) {
        var img = h.image ? '<img class="io-result-img" src="' + h.image + '" alt="">' : '';
        return '<a class="io-result-card" href="https://www.latestfoto.com/p/accommodation.html" target="_blank" rel="noopener">' + img +
          '<div class="io-result-info"><span class="io-result-name">' + escapeHtml(h.name) +
          '<span class="io-result-badge ' + dealBadgeClass(h.deal) + '">' + escapeHtml(h.deal || 'NORMAL') + '</span></span>' +
          '<span class="io-result-meta">' + (h.rating ? '\u2605 ' + h.rating : '') + '</span></div>' +
          '<span class="io-result-price">' + sym + (h.price || '\u2014') + '</span></a>';
      }).join('');
      addMsg('ai', '<div class="io-results-intro">\uD83C\uDFE8 Live hotel prices in ' + escapeHtml(cityName) + ' \u00B7 ' + cin + ' \u2192 ' + cout + '</div><div class="io-results-grid">' + cards + '</div>');
    }).catch(function () {
      removeTyping(typingId);
      addMsg('ai', "Couldn't reach live hotel data right now. Please try again shortly.");
    });
  }

  function handleDealQuery(cityName) {
    var typingId = showTyping();
    jsonp(GAS_URL + '?action=getDeals').then(function (allDeals) {
      removeTyping(typingId);
      var deals = (allDeals || []).filter(function (d) { return d.from && d.price; });
      if (cityName) {
        var cn = cityName.toLowerCase();
        var matches = deals.filter(function (d) { return (d.to || '').toLowerCase().indexOf(cn) > -1 || (d.from || '').toLowerCase().indexOf(cn) > -1; });
        if (matches.length) { deals = matches; }
      }
      if (!deals.length) { addMsg('ai', "No flight deals are available right now — the feed refreshes daily."); return; }
      deals = deals.slice(0, 4);
      var cards = deals.map(function (d) {
        return '<a class="io-result-card" href="' + d.link + '" target="_blank" rel="noopener">' +
          '<div class="io-result-info"><span class="io-result-name">' + escapeHtml(d.from) + ' \u2192 ' + escapeHtml(d.to) +
          '<span class="io-result-badge ' + dealBadgeClass(d.type) + '">' + escapeHtml(d.type || 'DEAL') + '</span></span>' +
          '<span class="io-result-meta">' + escapeHtml(d.route_type || 'One-way') + '</span></div>' +
          '<span class="io-result-price">\u20AC' + Math.round(d.price) + '</span></a>';
      }).join('');
      addMsg('ai', '<div class="io-results-intro">\uD83C\uDFF7 Today\'s flight deals</div><div class="io-results-grid">' + cards + '</div>');
    }).catch(function () {
      removeTyping(typingId);
      addMsg('ai', "Couldn't reach the flight deals feed. Please try again shortly.");
    });
  }

