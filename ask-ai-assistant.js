/* Latestfoto.com — Ask AI Assistant (merged travel + immigration) JS
   Built on top of the proven ImmigrationOpportunity.com widget logic,
   merged with the live hotel/flight/deal search from the Travel widget. */
(function () {

  var AFFILIATE_TAG = 'latestfotocom-20';

  // Claude-powered proxy (Google Apps Script) — handles chat, question
  // generation, classification, and Amazon keyword generation.
  var PROXY_URL = 'https://script.google.com/macros/s/AKfycbwX5TIkIg55a0aM5cDv7ESS20xlBiC6qPc0ZEVuifSLVm6BnlkKuf0jo-JPIflccPCY/exec';

  // Groq-powered proxy (Google Apps Script) — handles live hotel/flight/deal
  // search only. Real prices should never be generated by an LLM.
  var GAS_URL = 'https://script.google.com/macros/s/AKfycbyU7AWtPI72KuTwT5IXOvIHk7efrPii1yVtttBkt52Jzv1SaEOF1zQl_nlYd4BGmVfJ7A/exec';

  var CURRENCY_SYM = { USD:'$', EUR:'\u20AC', GBP:'\u00A3', INR:'\u20B9' };

  // Real affiliate destinations for travel-category product suggestions.
  // Static + deterministic — no AI call needed, no chance of a bad link.
  var TRAVEL_PRODUCTS = {
    accommodation: { icon:'\uD83C\uDFE8', name:'Hotels & Stays', desc:'Book accommodation', url:'https://www.latestfoto.com/p/accommodation.html' },
    flights:       { icon:'\u2708\uFE0F', name:'Air Tickets', desc:'Find flight deals', url:'https://www.latestfoto.com/p/airticket.html' },
    activities:    { icon:'\uD83C\uDFDF\uFE0F', name:'Tours & Activities', desc:'GetYourGuide', url:'https://www.getyourguide.com?partner_id=OGT26YS&utm_medium=online_publisher' },
    tickets:       { icon:'\uD83C\uDFAB', name:'Attraction Tickets', desc:'Tiqets', url:'https://www.tiqets.com/en/?partner=latestfoto.com' },
    freetours:     { icon:'\uD83D\uDEB6', name:'Free Walking Tours', desc:'GuruWalk', url:'https://www.guruwalk.com/?ref=ytglmuz8ne4qhj6e8lyn' }
  };

  /* ============================================================
     STEP 1 — Read page context (title, labels, body excerpt)
  ============================================================ */
  function getPageContext() {
    var title = '';
    var titleEl = document.querySelector('.post-title') ||
                  document.querySelector('h1.entry-title') ||
                  document.querySelector('h3.post-title') ||
                  document.querySelector('h1') ||
                  document.querySelector('title');
    if (titleEl) { title = titleEl.textContent.trim(); }

    var labelEls = document.querySelectorAll('.post-labels a, .labels a, a[rel="tag"]');
    var labels = [];
    for (var i = 0; i < labelEls.length; i++) {
      labels.push(labelEls[i].textContent.trim());
    }

    var bodyText = '';
    var bodyEl = document.querySelector('.post-body') ||
                 document.querySelector('.entry-content') ||
                 document.querySelector('article');
    if (bodyEl) { bodyText = bodyEl.textContent.replace(/\s+/g, ' ').trim().substring(0, 600); }

    return { title: title, labels: labels, body: bodyText };
  }

  /* ============================================================
     STEP 2 — Call the Claude proxy (text/plain POST avoids CORS preflight)
  ============================================================ */
  function callProxy(systemPrompt, userMessage, callback) {
    fetch(PROXY_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'text/plain' },
      body: JSON.stringify({
        system: systemPrompt,
        max_tokens: 500,
        messages: [{ role: 'user', content: userMessage }],
        origin: window.location.hostname
      })
    }).then(function (r) { return r.json(); })
      .then(function (data) {
        if (data && data.content && data.content[0]) {
          callback(null, data.content[0].text);
        } else {
          callback('No response', null);
        }
      }).catch(function (err) { callback(err, null); });
  }

  // JSONP helper for the Groq/live-search proxy (GET + callback only).
  function jsonp(url) {
    return new Promise(function (resolve, reject) {
      var cbName = 'cb_' + Math.floor(Math.random() * 1e9);
      var script = document.createElement('script');
      window[cbName] = function (data) { resolve(data); delete window[cbName]; script.remove(); };
      script.onerror = function () { delete window[cbName]; script.remove(); reject(new Error('JSONP failed')); };
      script.src = url + (url.indexOf('?') > -1 ? '&' : '?') + 'callback=' + cbName;
      document.head.appendChild(script);
    });
  }

  /* ============================================================
     STEP 3 — ONE classification call: category + topic + 6 questions
     Replaces two separate calls from the original widget with one,
     to cut proxy round-trips in half on page load.
  ============================================================ */
  function classifyAndSuggest(ctx, callback) {
    var systemPrompt =
      'You classify an article for a combined travel + immigration website and generate 6 short suggested reader questions. ' +
      'Return ONLY strict JSON, no markdown, no explanation, matching exactly this shape: ' +
      '{"category":"travel|immigration|general","topic":"short topic name, e.g. a city or a visa name","questions":["q1","q2","q3","q4","q5","q6"]}. ' +
      '"category" is "travel" if the article is primarily about a destination, trip, hotel, or activity. ' +
      '"category" is "immigration" if it is primarily about visas, residency, work permits, citizenship, or moving abroad. ' +
      'Otherwise use "general". Each question must be under 12 words and directly about the article topic.';

    var userMsg = 'Article title: ' + ctx.title + '\n' +
      'Labels: ' + ctx.labels.join(', ') + '\n' +
      'Excerpt: ' + ctx.body.substring(0, 400);

    callProxy(systemPrompt, userMsg, function (err, response) {
      if (err || !response) { callback(fallbackClassification(ctx)); return; }
      try {
        var clean = response.trim().replace(/```json|```/g, '').trim();
        var parsed = JSON.parse(clean);
        if (!parsed.category || !Array.isArray(parsed.questions)) { throw new Error('bad shape'); }
        callback(parsed);
      } catch (e) {
        callback(fallbackClassification(ctx));
      }
    });
  }

  function fallbackClassification(ctx) {
    return {
      category: 'general',
      topic: ctx.title,
      questions: ['Tell me more about ' + ctx.title]
    };
  }

  /* ============================================================
     STEP 4 — Build widget shell
  ============================================================ */
  var currentCtx = null;
  var currentClassification = null;

  function badgeHtml(category, topic) {
    var map = {
      travel: { cls: 'io-badge-travel', icon: '\u2708\uFE0F', label: topic || 'Travel' },
      immigration: { cls: 'io-badge-immigration', icon: '\uD83D\uDEC2', label: topic || 'Visas & Immigration' },
      general: { cls: 'io-badge-general', icon: '\uD83C\uDF0D', label: 'General' }
    };
    var m = map[category] || map.general;
    return '<span class="io-ai-badge ' + m.cls + '">' + m.icon + ' ' + escapeHtml(m.label) + '</span>';
  }

  function escapeHtml(str) {
    var div = document.createElement('div');
    div.textContent = str || '';
    return div.innerHTML;
  }

  function buildWidget() {
    var ctx = getPageContext();
    currentCtx = ctx;
    var topicHint = ctx.title ? ' about "' + ctx.title + '"' : '';

    var wrap = document.getElementById('ioAiWidget');
    if (!wrap) { return; }

    wrap.innerHTML =
      '<div class="io-ai-header">' +
        '<div class="io-ai-avatar">\uD83E\uDD16</div>' +
        '<div class="io-ai-header-text">' +
          '<h3>Ask AI Assistant</h3>' +
          '<p><span id="ioBadgeSlot">' + badgeHtml('general', '') + '</span></p>' +
        '</div>' +
        '<div class="io-ai-status"><div class="io-ai-dot"></div> Online</div>' +
      '</div>' +
      '<div class="io-suggestions">' +
        '<span class="io-sug-label">\uD83D\uDCA1 Questions about this article</span>' +
        '<div class="io-sug-pills" id="ioSugPills"><span class="io-sug-pill" style="opacity:0.5">Loading questions...</span></div>' +
      '</div>' +
      '<div class="io-chat-area" id="ioChatArea">' +
        '<div class="io-msg ai">' +
          '<div class="io-msg-avatar">\uD83E\uDD16</div>' +
          '<div class="io-msg-bubble">' +
            '\uD83D\uDC4B <strong>Hello! I\'m your AI Assistant.</strong><br/><br/>' +
            'I\'ve read the article' + topicHint + '. Ask me about hotels, flights, trip planning, or visas &amp; immigration — I\'ll also suggest helpful resources! \uD83C\uDF0D' +
          '</div>' +
        '</div>' +
      '</div>' +
      '<div class="io-input-wrap">' +
        '<div class="io-input-row">' +
          '<textarea class="io-input" id="ioInput" placeholder="Ask about hotels, flights, visas, immigration..." rows="1"></textarea>' +
          '<button class="io-send-btn" id="ioSendBtn" title="Send">\u27A4</button>' +
        '</div>' +
      '</div>' +
      '<p class="io-disclaimer">\u26A0 This AI provides general information only. Always verify prices directly and immigration details with official government sources or a licensed consultant.</p>';

    classifyAndSuggest(ctx, function (classification) {
      currentClassification = classification;

      var badgeSlot = document.getElementById('ioBadgeSlot');
      if (badgeSlot) { badgeSlot.innerHTML = badgeHtml(classification.category, classification.topic); }

      var pills = document.getElementById('ioSugPills');
      if (pills) {
        var html = '';
        for (var i = 0; i < classification.questions.length && i < 6; i++) {
          html += '<span class="io-sug-pill">' + escapeHtml(classification.questions[i]) + '</span>';
        }
        pills.innerHTML = html || '<span class="io-sug-pill">Tell me about ' + escapeHtml(ctx.title) + '</span>';
      }
    });

    document.getElementById('ioSendBtn').addEventListener('click', function () {
      sendMessage(document.getElementById('ioInput').value.trim());
    });
    document.getElementById('ioInput').addEventListener('keydown', function (e) {
      if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); sendMessage(this.value.trim()); }
    });
    document.getElementById('ioInput').addEventListener('input', function () {
      this.style.height = 'auto';
      this.style.height = Math.min(this.scrollHeight, 120) + 'px';
    });
    document.getElementById('ioSugPills').addEventListener('click', function (e) {
      if (e.target.className.indexOf('io-sug-pill') !== -1) { sendMessage(e.target.textContent); }
    });
  }

  /* ============================================================
     STEP 5 — Live search intent detection (hotel / flight / deal)
     Only fires for genuinely live, price-bearing queries — everything
     else (including all immigration questions) goes to the AI.
  ============================================================ */
  function detectLiveSearchIntent(text) {
    var lower = text.toLowerCase();
    if (/\b(hotel|hotels|stay|accommodation|room|place to stay)\b/.test(lower)) { return 'hotel'; }
    if (/\b(flight|flights|fly|airfare|plane ticket)\b/.test(lower)) { return 'flight'; }
    if (/\b(deal|deals|cheap fare|cheap flight|error fare)\b/.test(lower)) { return 'deal'; }
    return null;
  }

  function guessCityFromText(text, ctx) {
    // Prefer an explicit city mention in the message; else fall back to
    // the article's classified topic if it's a travel article.
    var words = text.replace(/[^a-zA-Z\s]/g, '').split(/\s+/).filter(function (w) { return w.length > 2; });
    var lastCapitalized = null;
    for (var i = 0; i < words.length; i++) {
      if (/^[A-Z]/.test(words[i])) { lastCapitalized = words[i]; }
    }
    if (lastCapitalized) { return lastCapitalized; }
    if (currentClassification && currentClassification.category === 'travel' && currentClassification.topic) {
      return currentClassification.topic;
    }
    return ctx.title;
  }

  function dealBadgeClass(deal) {
    var d = (deal || 'NORMAL').toUpperCase();
    if (d === 'VERY CHEAP') return 'verycheap';
    if (d === 'CHEAP') return 'cheap';
    return '';
  }

  function handleHotelQuery(cityName) {
    var typingId = showTyping();
    var checkin = new Date(); checkin.setDate(checkin.getDate() + 7);
    var checkout = new Date(); checkout.setDate(checkout.getDate() + 10);
    var cin = checkin.toISOString().slice(0, 10);
    var cout = checkout.toISOString().slice(0, 10);
    var url = GAS_URL + '?action=searchHotels&city=' + encodeURIComponent(cityName) +
      '&checkin=' + cin + '&checkout=' + cout + '&adults=2&currency=USD&stars=all';

    jsonp(url).then(function (data) {
      removeTyping(typingId);
      if (!data || !data.hotels || !data.hotels.length) {
        addMsg('ai', 'No live hotel prices came back for ' + escapeHtml(cityName) + ' right now — try different dates or check <a href="https://www.latestfoto.com/p/accommodation.html" target="_blank" rel="noopener">our accommodation page</a>.');
        return;
      }
      var sym = CURRENCY_SYM.USD;
      var cards = data.hotels.slice(0, 4).map(function (h) {
        var img = h.image ? '<img class="io-result-img" src="' + h.image + '" alt="">' : '';
        return '<a class="io-result-card" href="https://www.latestfoto.com/p/accommodation.html" target="_blank" rel="noopener">' + img +
          '<div class="io-result-info"><span class="io-result-name">' + escapeHtml(h.name) +
          '<span class="io-result-badge ' + dealBadgeClass(h.deal) + '">' + escapeHtml(h.deal || 'NORMAL') + '</span></span>' +
          '<span class="io-result-meta">' + (h.rating ? '\u2605 ' + h.rating : '') + '</span></div>' +
          '<span class="io-result-price">' + sym + (h.price || '\u2014') + '</span></a>';
      }).join('');
      addMsg('ai', '<div class="io-results-intro">\uD83C\uDFE8 Live hotel prices in ' + escapeHtml(cityName) + ' \u00B7 ' + cin + ' \u2192 ' + cout + '</div><div class="io-results-grid">' + cards + '</div>');
    }).catch(function () {
      removeTyping(typingId);
      addMsg('ai', "Couldn't reach live hotel data right now. Please try again shortly.");
    });
  }

  function handleDealQuery(cityName) {
    var typingId = showTyping();
    jsonp(GAS_URL + '?action=getDeals').then(function (allDeals) {
      removeTyping(typingId);
      var deals = (allDeals || []).filter(function (d) { return d.from && d.price; });
      if (cityName) {
        var cn = cityName.toLowerCase();
        var matches = deals.filter(function (d) { return (d.to || '').toLowerCase().indexOf(cn) > -1 || (d.from || '').toLowerCase().indexOf(cn) > -1; });
        if (matches.length) { deals = matches; }
      }
      if (!deals.length) { addMsg('ai', "No flight deals are available right now — the feed refreshes daily."); return; }
      deals = deals.slice(0, 4);
      var cards = deals.map(function (d) {
        return '<a class="io-result-card" href="' + d.link + '" target="_blank" rel="noopener">' +
          '<div class="io-result-info"><span class="io-result-name">' + escapeHtml(d.from) + ' \u2192 ' + escapeHtml(d.to) +
          '<span class="io-result-badge ' + dealBadgeClass(d.type) + '">' + escapeHtml(d.type || 'DEAL') + '</span></span>' +
          '<span class="io-result-meta">' + escapeHtml(d.route_type || 'One-way') + '</span></div>' +
          '<span class="io-result-price">\u20AC' + Math.round(d.price) + '</span></a>';
      }).join('');
      addMsg('ai', '<div class="io-results-intro">\uD83C\uDFF7 Today\'s flight deals</div><div class="io-results-grid">' + cards + '</div>');
    }).catch(function () {
      removeTyping(typingId);
      addMsg('ai', "Couldn't reach the flight deals feed. Please try again shortly.");
    });
  }

  /* ============================================================
     STEP 6 — General AI chat (merged travel + immigration persona)
  ============================================================ */
  function callAI(userMessage, ctx, callback) {
    var systemPrompt =
      'You are "Ask AI Assistant" on latestfoto.com, a friendly and knowledgeable travel + immigration advisor. ' +
      'The visitor is reading an article titled: "' + ctx.title + '". ' +
      'Article labels: ' + (ctx.labels.length ? ctx.labels.join(', ') : 'general') + '. ' +
      'Answer questions about travel planning (hotels, flights, itineraries, activities, local tips) AND about immigration/visas (eligibility, application steps, timelines, requirements) as relevant to what is asked. ' +
      'Stay focused on the topic of this article when the question is ambiguous. ' +
      'Be warm, accurate and conversational. Keep answers to 4-5 sentences. Do not use markdown headers or bullet points. ' +
      'For visa/immigration questions, note that requirements vary by nationality and change over time, and end with: ' +
      'For the most accurate information, please check the official government immigration website or consult a licensed immigration consultant. ' +
      'For travel/price questions, remind the user to verify current prices directly with the provider. Be AdSense-safe always.';

    callProxy(systemPrompt, userMessage, function (err, response) {
      callback(err ? 'I could not process that right now. Please try again!' : response);
    });
  }

  /* ============================================================
     STEP 7 — Product suggestions, branched by category
  ============================================================ */
  function amazonUrl(keyword) {
    return 'https://www.amazon.com/s?k=' + encodeURIComponent(keyword.trim()) + '&tag=' + AFFILIATE_TAG;
  }

  function getAmazonKeywords(aiText, userQuestion, ctx, callback) {
    var systemPrompt =
      'You generate Amazon search keywords for books/resources related to an immigration topic. ' +
      'Given the article topic and an AI answer, generate 2 short Amazon search keywords (under 6 words each). ' +
      'Return ONLY a JSON array of 2 strings, no markdown. Example: ["Canada immigration guide book","Express Entry preparation 2025"]';
    var userMsg = 'Article title: ' + ctx.title + '\nLabels: ' + ctx.labels.join(', ') +
      '\nUser question: ' + userQuestion + '\nAI answer summary: ' + aiText.substring(0, 200);

    callProxy(systemPrompt, userMsg, function (err, response) {
      if (err || !response) { callback([ctx.title + ' guide book']); return; }
      try {
        var clean = response.trim().replace(/```json|```/g, '').trim();
        var keywords = JSON.parse(clean);
        if (!Array.isArray(keywords) || !keywords.length) { throw new Error('bad'); }
        callback(keywords.slice(0, 2));
      } catch (e) { callback([ctx.title + ' guide book']); }
    });
  }

  function buildAmazonProductCards(keywords) {
    if (!keywords || !keywords.length) return '';
    var html = '<div class="io-products"><span class="io-prod-label">\uD83D\uDCDA Helpful resources</span>';
    keywords.forEach(function (kw) {
      var displayName = kw.replace(/\b\w/g, function (c) { return c.toUpperCase(); });
      html += '<a href="' + amazonUrl(kw) + '" target="_blank" rel="noopener sponsored" class="io-product-card">' +
        '<span class="io-product-icon">\uD83D\uDCD8</span>' +
        '<div class="io-product-info"><span class="io-product-name">' + escapeHtml(displayName) + '</span></div>' +
        '<span class="io-product-cta">View \u2192</span></a>';
    });
    return html + '</div>';
  }

  function buildTravelProductCards(keys) {
    var html = '<div class="io-products"><span class="io-prod-label">\uD83E\uDDED Suggested for you</span>';
    keys.forEach(function (key) {
      var p = TRAVEL_PRODUCTS[key];
      if (!p) return;
      html += '<a href="' + p.url + '" target="_blank" rel="noopener sponsored" class="io-product-card">' +
        '<span class="io-product-icon">' + p.icon + '</span>' +
        '<div class="io-product-info"><span class="io-product-name">' + p.name + '</span><span class="io-product-desc">' + p.desc + '</span></div>' +
        '<span class="io-product-cta">View \u2192</span></a>';
    });
    return html + '</div>';
  }

  function appendProductSuggestions(bubbleEl, aiText, userQuestion, ctx) {
    var category = currentClassification ? currentClassification.category : 'general';
    if (category === 'immigration') {
      getAmazonKeywords(aiText, userQuestion, ctx, function (keywords) {
        bubbleEl.insertAdjacentHTML('beforeend', buildAmazonProductCards(keywords));
        scrollChatToBottom();
      });
    } else if (category === 'travel') {
      bubbleEl.insertAdjacentHTML('beforeend', buildTravelProductCards(['accommodation', 'flights', 'activities', 'tickets']));
      scrollChatToBottom();
    }
    // category === 'general': no product panel, keep it clean
  }

  /* ============================================================
     STEP 8 — Chat rendering helpers
  ============================================================ */
  function addMsg(role, html) {
    var area = document.getElementById('ioChatArea');
    var div = document.createElement('div');
    div.className = 'io-msg ' + role;
    var icon = (role === 'ai') ? '\uD83E\uDD16' : '\uD83D\uDC64';
    div.innerHTML = '<div class="io-msg-avatar">' + icon + '</div><div class="io-msg-bubble">' + html + '</div>';
    area.appendChild(div);
    scrollChatToBottom();
    return div.querySelector('.io-msg-bubble');
  }

  function scrollChatToBottom() {
    var area = document.getElementById('ioChatArea');
    if (area) area.scrollTop = area.scrollHeight;
  }

  var typingCounter = 0;
  function showTyping() {
    var id = 'ioTyping' + (++typingCounter);
    var area = document.getElementById('ioChatArea');
    var div = document.createElement('div');
    div.className = 'io-msg ai io-typing';
    div.id = id;
    div.innerHTML = '<div class="io-msg-avatar">\uD83E\uDD16</div><div class="io-msg-bubble"><div class="io-typing-dots"><span></span><span></span><span></span></div></div>';
    area.appendChild(div);
    scrollChatToBottom();
    return id;
  }
  function removeTyping(id) {
    var t = document.getElementById(id);
    if (t) { t.parentNode.removeChild(t); }
  }

  /* ============================================================
     STEP 9 — Message dispatch
  ============================================================ */
  function sendMessage(text) {
    if (!text || !text.trim()) return;
    var btn = document.getElementById('ioSendBtn');
    var input = document.getElementById('ioInput');
    var ctx = getPageContext();

    addMsg('user', escapeHtml(text));
    input.value = '';
    input.style.height = 'auto';
    btn.disabled = true;

    var liveIntent = detectLiveSearchIntent(text);

    if (liveIntent === 'hotel') {
      var city = guessCityFromText(text, ctx);
      handleHotelQuery(city);
      btn.disabled = false;
      input.focus();
      return;
    }
    if (liveIntent === 'flight' || liveIntent === 'deal') {
      var cityForDeal = guessCityFromText(text, ctx);
      handleDealQuery(cityForDeal);
      btn.disabled = false;
      input.focus();
      return;
    }

    var typingId = showTyping();
    callAI(text, ctx, function (aiText) {
      removeTyping(typingId);
      var formatted = aiText.replace(/\n\n/g, '<br><br>').replace(/\n/g, '<br>');
      var bubble = addMsg('ai', formatted);
      appendProductSuggestions(bubble, aiText, text, ctx);
      btn.disabled = false;
      input.focus();
    });
  }

  /* ============================================================
     STEP 10 — Init
  ============================================================ */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', buildWidget);
  } else {
    buildWidget();
  }

})();
