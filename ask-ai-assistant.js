  /* ============================================================
     STEP 7 — Product suggestions, branched by category
  ============================================================ */
  function amazonUrl(keyword) {
    return 'https://www.amazon.com/s?k=' + encodeURIComponent(keyword.trim()) + '&tag=' + AFFILIATE_TAG;
  }

  function getAmazonKeywords(aiText, userQuestion, ctx, callback) {
    var systemPrompt =
      'You generate Amazon search keywords for books/resources related to an immigration topic. ' +
      'Given the article topic and an AI answer, generate 2 short Amazon search keywords (under 6 words each). ' +
      'Return ONLY a JSON array of 2 strings, no markdown. Example: ["Canada immigration guide book","Express Entry preparation 2025"]';
    var userMsg = 'Article title: ' + ctx.title + '\nLabels: ' + ctx.labels.join(', ') +
      '\nUser question: ' + userQuestion + '\nAI answer summary: ' + aiText.substring(0, 200);

    callProxy(systemPrompt, userMsg, function (err, response) {
      if (err || !response) { callback([ctx.title + ' guide book']); return; }
      try {
        var clean = response.trim().replace(/```json|```/g, '').trim();
        var keywords = JSON.parse(clean);
        if (!Array.isArray(keywords) || !keywords.length) { throw new Error('bad'); }
        callback(keywords.slice(0, 2));
      } catch (e) { callback([ctx.title + ' guide book']); }
    });
  }

  function buildAmazonProductCards(keywords) {
    if (!keywords || !keywords.length) return '';
    var html = '<div class="io-products"><span class="io-prod-label">\uD83D\uDCDA Helpful resources</span>';
    keywords.forEach(function (kw) {
      var displayName = kw.replace(/\b\w/g, function (c) { return c.toUpperCase(); });
      html += '<a href="' + amazonUrl(kw) + '" target="_blank" rel="noopener sponsored" class="io-product-card">' +
        '<span class="io-product-icon">\uD83D\uDCD8</span>' +
        '<div class="io-product-info"><span class="io-product-name">' + escapeHtml(displayName) + '</span></div>' +
        '<span class="io-product-cta">View \u2192</span></a>';
    });
    return html + '</div>';
  }

  function buildTravelProductCards(keys) {
    var html = '<div class="io-products"><span class="io-prod-label">\uD83E\uDDED Suggested for you</span>';
    keys.forEach(function (key) {
      var p = TRAVEL_PRODUCTS[key];
      if (!p) return;
      html += '<a href="' + p.url + '" target="_blank" rel="noopener sponsored" class="io-product-card">' +
        '<span class="io-product-icon">' + p.icon + '</span>' +
        '<div class="io-product-info"><span class="io-product-name">' + p.name + '</span><span class="io-product-desc">' + p.desc + '</span></div>' +
        '<span class="io-product-cta">View \u2192</span></a>';
    });
    return html + '</div>';
  }

  function appendProductSuggestions(bubbleEl, aiText, userQuestion, ctx) {
    var category = currentClassification ? currentClassification.category : 'general';
    if (category === 'immigration') {
      getAmazonKeywords(aiText, userQuestion, ctx, function (keywords) {
        bubbleEl.insertAdjacentHTML('beforeend', buildAmazonProductCards(keywords));
        scrollChatToBottom();
      });
    } else if (category === 'travel') {
      bubbleEl.insertAdjacentHTML('beforeend', buildTravelProductCards(['accommodation', 'flights', 'activities', 'tickets']));
      scrollChatToBottom();
    }
    // category === 'general': no product panel, keep it clean
  }

  /* ============================================================
     STEP 8 — Chat rendering helpers
  ============================================================ */
  function addMsg(role, html) {
    var area = document.getElementById('ioChatArea');
    var div = document.createElement('div');
    div.className = 'io-msg ' + role;
    var icon = (role === 'ai') ? '\uD83E\uDD16' : '\uD83D\uDC64';
    div.innerHTML = '<div class="io-msg-avatar">' + icon + '</div><div class="io-msg-bubble">' + html + '</div>';
    area.appendChild(div);
    scrollChatToBottom();
    return div.querySelector('.io-msg-bubble');
  }

  function scrollChatToBottom() {
    var area = document.getElementById('ioChatArea');
    if (area) area.scrollTop = area.scrollHeight;
  }

  var typingCounter = 0;
  function showTyping() {
    var id = 'ioTyping' + (++typingCounter);
    var area = document.getElementById('ioChatArea');
    var div = document.createElement('div');
    div.className = 'io-msg ai io-typing';
    div.id = id;
    div.innerHTML = '<div class="io-msg-avatar">\uD83E\uDD16</div><div class="io-msg-bubble"><div class="io-typing-dots"><span></span><span></span><span></span></div></div>';
    area.appendChild(div);
    scrollChatToBottom();
    return id;
  }
  function removeTyping(id) {
    var t = document.getElementById(id);
    if (t) { t.parentNode.removeChild(t); }
  }

  /* ============================================================
     STEP 9 — Message dispatch
  ============================================================ */
  function sendMessage(text) {
    if (!text || !text.trim()) return;
    var btn = document.getElementById('ioSendBtn');
    var input = document.getElementById('ioInput');
    var ctx = getPageContext();

    addMsg('user', escapeHtml(text));
    input.value = '';
    input.style.height = 'auto';
    btn.disabled = true;

    var liveIntent = detectLiveSearchIntent(text);

    // Log every question asked, regardless of how it's routed.
    logQuery(text, ctx, { category: currentClassification ? currentClassification.category : null, intent: liveIntent });

    if (liveIntent === 'hotel') {
      var city = guessCityFromText(text, ctx);
      handleHotelQuery(city);
      btn.disabled = false;
      input.focus();
      return;
    }
    if (liveIntent === 'flight' || liveIntent === 'deal') {
      var cityForDeal = guessCityFromText(text, ctx);
      handleDealQuery(cityForDeal);
      btn.disabled = false;
      input.focus();
      return;
    }
    if (liveIntent === 'concert') {
      handleConcertQuery();
      btn.disabled = false;
      input.focus();
      return;
    }
    if (liveIntent === 'event') {
      handleEventsQuery();
      btn.disabled = false;
      input.focus();
      return;
    }
    if (liveIntent === 'freetours') {
      var cityForTours = guessCityFromText(text, ctx);
      handleFreeToursQuery(cityForTours);
      btn.disabled = false;
      input.focus();
      return;
    }
    if (liveIntent === 'destinations') {
      var cityForDestinations = guessCityFromText(text, ctx);
      handleDestinationsQuery(cityForDestinations);
      btn.disabled = false;
      input.focus();
      return;
    }

    var typingId = showTyping();
    callAI(text, ctx, function (aiText) {
      removeTyping(typingId);
      var formatted = aiText.replace(/\n\n/g, '<br><br>').replace(/\n/g, '<br>');
      var bubble = addMsg('ai', formatted);
      appendProductSuggestions(bubble, aiText, text, ctx);
      btn.disabled = false;
      input.focus();
    });
  }

